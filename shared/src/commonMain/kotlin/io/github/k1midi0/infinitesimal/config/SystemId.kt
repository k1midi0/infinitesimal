package io.github.k1midi0.infinitesimal.config

/**
 * 请求是"谁"发出的——它同时就是这个请求所属的**缓存池**。
 *
 * 端点把 `user_id` 用在三件事上（官方《限速与隔离》原文）：**内容安全隔离**、**KVCache 隔离**、**调度
 * 隔离**。所以"每个系统一份"不是我们发明的分层，是端点已经提供的那一层。
 *
 * **代价几乎为零。** 缓存按"前缀单元"完整匹配，而各个系统的 system 提示词本来就完全不同——它们
 * 之间没有任何可共享的前缀，隔离因此不损失任何命中。（这一条要一直成立：哪天两个系统开始共享一段
 * 大的静态前缀，就该重新想。）
 *
 * 买到的三样：
 *
 *  1. **隔离**：一个系统的请求不会挤掉另一个系统的缓存单元。
 *  2. **归因**：哪个系统的命中率是多少，看 `usage` 就能分开算。
 *  3. **可诊断**：这类"命中恒为 0"的问题，有分层才分得清是"同一个池里也不命中"（缓存没生效）
 *     还是"跨池本来就不该命中"（隔离按文档在工作）。
 *
 * 用闭合枚举而不是裸字符串：`user_id` 写错一个字母不报错，只是**静默地换了一个缓存池**——命中率
 * 掉下去，而没有任何地方看起来不对。这与 [ThinkingMode]、[ReasoningEffort] 是同一条理由。
 *
 * 端点的约束（官方原文）：须匹配 `[a-zA-Z0-9\-_]+`，最长 512，**不得包含隐私信息**。
 */
enum class SystemId(val userId: String) {
    /** 观察器：把物体渲染成文字。 */
    RENDERER("inf-renderer"),

    /** 导演：剧本、伏笔、日程、补写世界事实。 */
    DIRECTOR("inf-director"),

    /** 扮演某个角色（剧情 NPC 与活跃氛围 NPC 共用一池）。 */
    NPC("inf-npc"),

    /** 判定：合不合理、该有什么后果。 */
    JUDGE("inf-judge"),

    /** 摘要与笔记的整理。 */
    SUMMARIZER("inf-summarizer"),
    ;

    companion object {
        /** 界面上给人看的名字，与线上发的字符串分开写，避免"界面一个词、请求另一个词"。 */
        fun labelOf(id: SystemId): String = id.userId
    }
}
