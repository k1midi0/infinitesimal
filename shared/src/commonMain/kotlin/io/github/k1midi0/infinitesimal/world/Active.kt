package io.github.k1midi0.infinitesimal.world

import kotlinx.serialization.Serializable

/**
 * **这个角色现在是活跃的**（§3.2.1、§12 第 46 项）。
 *
 * ## 它是什么，以及它不是
 *
 * 一个氛围 NPC 平时**根本不是 AI**：它在循环里的哪一格由 [Cycle] 查表得出，零模型调用。被指向之后它
 * 转成**活跃氛围 NPC**——功能上等同剧情 NPC（有持久上下文、能写笔记），但**保留它的状态循环**。
 *
 * **[active][Entity.active] 不是"要不要调模型"那个开关。** 唤醒的判据只有一条，而且与活跃无关：
 * **被判定点名**（`GameSession.hearAndReact`）。§3.2 那句「投递总是发生，唤醒才是例外」说的是同一件事
 * ——隔壁桌永远收得到"他刚才说了什么"，而醒过来接话只有被指向的人才会。所以活跃**不**让一个角色
 * 每回合都烧一次调用。
 *
 * 它管的是另外三件，而三件都是同一句话的后果——**「它此刻没有在走循环」**：
 *
 *  1. **它自己的笔记回到眼前**（[Entity.notes] 的 [live] 那些）。不活跃时那些笔记**保留但不注入**
 *     （§3.2.1）——库里一直在，只是不装进提示词。
 *  2. **它能写笔记**。不活跃时那只手会打回：写下来的东西它自己看不见，那等于把记忆丢进一个抽屉。
 *  3. **它能宣告回归**（`arrive` 那只手），回到循环上的某一格。
 *
 * ## 回归为什么由它自己宣告，而不是代码算出来
 *
 * 「回到循环上」这句话的一多半只有它自己知道：它这一趟做完没有、还想不想接着做，都不是代码读得出来
 * 的（循环那一格写的是「招呼客人」，而"回到酒馆自己的位置上"是它的判断，拿字符串比会永远不等，
 * 症状是**它永远不回归**）。
 *
 * 于是：**它自己说"我回去了"，而代码只确认它有没有资格说这句话**（[canArrive]）。资格是两条——
 * **此刻那一格正是它要回的那一格**，而且**它人真的在那一格的地点附近**（§14.44 把坐标加进每一格
 * 之后，这一条才查得了）。这不是偷懒：与 `no_change`、`act` 是同一种做法，**模型提出，代码只校验**。
 *
 * **回归不额外记任何东西。** 它这一趟的经历留在两处本来就在的地方：**对话历史**（累积的多轮上下文，
 * 压过也在）与**它自己写的那些笔记**。为回归再写一份摘要是第二种记法，而两种记法迟早会不一致。
 *
 * ## 它落在世界状态里，不是会话内存里
 *
 * 与 `cycle`、`todos`、`notes` 并排放在 [Entity] 上。理由与笔记那一条相同：它是**真相**——重启一次
 * "这个矮人是不是活跃的"不该变，而笔记保留不注入这件事本来就已经写在实体上了，两半得在同一个地方。
 *
 * @property since 从什么时候起它没在走循环。**只作归因**——事后要能回答"它当时是从哪一刻开始脱轨的"。
 * @property target 它脱轨时正要去的那一格。**只作归因**：判"回没回去"由 [canGo] 读此刻那一格，不读
 *   这一个（§14.45 改了那条判据，理由写在 [canGo] 上）。导演把整张作息换掉时，这一格如果不在新表里
 *   就会被清成 null（`CyclePlanner.apply`）——留着它就是留一个永远等不到的时刻。
 */
@Serializable
data class Active(
    val since: WorldTime,
    val target: Beat? = null,
)

/**
 * **它现在能不能说"我回去了"，以及不能的话差在哪一条上**（§14.43、§14.45）。
 *
 * 三条判据都写在各字段里；三条全中才算回得去（[can]）。**一份答复给三条**而不是只给一个是非，是
 * 因为拒绝话术要说清它该往哪修（§1.5 第三条：理由不撒谎）——[io.github.k1midi0.infinitesimal.npc.Npc]
 * 的 `arrive` 那只手就是照着这三栏写拒绝理由的。
 */
data class Arriving(
    /** 此刻循环规定的那一格。循环是空的时这里为 null。 */
    val beat: Beat?,
    /** 它人是不是真的在那一格的地点附近。 */
    val atThePlace: Boolean,
    /** 它自己报上来的那句话**是不是那一格的原文**。 */
    val saidTheSame: Boolean,
) {
    val can: Boolean get() = beat != null && atThePlace && saidTheSame
}

/**
 * **它现在能不能说"我回去了"。**
 *
 * ## 三条判据
 *
 *  1. **有那一格**（此刻的循环不是空的）。
 *  2. **它人真的在那一格的地点附近**（比坐标，容差 [ARRIVE_TOLERANCE_CM]）。
 *  3. **它报上来的那句话就是那一格的原文**（比 [Beat.state]，去掉首尾空白）。
 *
 * ## 为什么不再拿"它脱轨时想去的那一格"（[Active.target]）当判据（§14.45）
 *
 * 原来比的是 [Active.target] 与此刻那一格的 [Beat.atMinute]。这条路在真游戏里**是死的**：全项目
 * 生产代码里 `Active` 只在探测到"卡住"时才被创建（§14.45），而在此之前没有任何一处会设那个
 * `target`，于是 `canArrive` 恒为 false——只有测试与探针手动设过它才活。现在改成"报的原文与此刻
 * 那一格对得上"，那个字段就只剩归因的作用（它也仍然有用：事后要能回答"它当时想去哪一格"）。
 *
 * ## 为什么比的是那一格、不是别的东西
 *
 * 两句不同的状态恰好在不同时刻指向同一件事（「招呼客人」与「在柜台后面忙」）是常事，而**同一句话
 * 出现在两格里**同样是常事（午市与晚市都写「招呼客人」）。所以 [Beat.state] 只用来**验它报的那句
 * 话**（模型手里有原文，抄错就是它没看），**不是**用来判"这是哪一格"的；真正定"是哪一格"的仍是
 * 时刻——那一刻循环规定的就是它。
 *
 * ## 为什么要加地点这一条（§14.44）
 *
 * 2026-09-26 把位置从循环里拿掉时，这一条查不了（循环里没有地点），所以"到没到"只能由它自己说。
 * §14.44 把坐标加回每一格（作为**基线**，不是事实），于是代码有了第二个可查的判据：**它是不是真的
 * 站在那个地方**。没有这一条，一个还没走回酒馆的矮人只要在门口报一句原文，就能宣称"我回去了"，
 * 而它还在三条街以外——那种回归在世界上没有任何痕迹能露馅。
 *
 * 容差是必须的：一格的地点是一个**点**，而"站在那张桌子后面"是一片地方（而且它自己看不到自己的
 * 坐标，报不出来）；但容差**必须小于一格**——[ARRIVE_TOLERANCE_CM] 取六十厘米，理由写在那个常量上。
 *
 * 没有循环（[Cycle.isEmpty]）时永远为 false：它没有可回的那一格，而"回一个不存在的地方"不该被接受。
 */
fun Active.canGo(cycle: Cycle, now: WorldTime, at: Entity, said: String): Arriving {
    val here = cycle.beatAt(now)
    return Arriving(
        beat = here,
        atThePlace = here != null && nearEnough(at.x, at.y, at.z, here),
        saidTheSame = here != null && here.state.trim() == said.trim(),
    )
}

/**
 * 一次回归认多近算"到了"：**六十厘米**（一个地形格是五十厘米）。
 *
 * 它是单个常量，因为两头都要用同一把尺子：代码用它判回归，而拒绝话术里把它写给模型看
 * （"你还差着 N 厘米"），两处不一致就会出现"差一点却说不清差多少"。
 *
 * ## 为什么不是"两米，一格多一点"（§14.45 收紧的那一下）
 *
 * 两米比一格还宽，于是**"站在隔壁那一格"也算到了**——而那正好让"它真的走到了那儿"这件事失效：
 * 一个在 (1200,200) 的人报一次 `arrive`，(1000,200) 那一格也会放行。六十厘米比一格略宽，读法因此是
 * **"它在那一格里"**：模型报不出厘米（它看不到自己的坐标），而代码也不必要求一个点。
 */
const val ARRIVE_TOLERANCE_CM: Int = 60

/** 实体此刻的位置离这一格的地点够不够近（三个方向各算，用的还是 [ARRIVE_TOLERANCE_CM]）。 */
fun nearEnough(x: Int, y: Int, z: Int, beat: Beat): Boolean =
    kotlin.math.abs(x - beat.x) <= ARRIVE_TOLERANCE_CM &&
        kotlin.math.abs(y - beat.y) <= ARRIVE_TOLERANCE_CM &&
        kotlin.math.abs(z - beat.z) <= ARRIVE_TOLERANCE_CM
