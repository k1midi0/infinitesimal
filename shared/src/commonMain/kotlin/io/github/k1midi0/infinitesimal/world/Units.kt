package io.github.k1midi0.infinitesimal.world

/**
 * 世界坐标的基准单位是**厘米**（附录 A.2，2026-09-24 定的）。
 *
 * 为什么不是米：形状的最小单位是 5 厘米（[VOXEL_CM]），而一张桌子高 80 厘米、一个酒杯高 12 厘米
 * ——用米当单位，这些数一个都写不出来。厘米是整数，5 厘米格是它的一份，不需要第二条单位。
 *
 * **米还在，但它只是一条换算线**：空间框（射线、包围框、俯视图网格）按 1 米格处理（附录 A.12），
 * 那个格子就是 [CM_PER_METRE] 厘米。所以世界里只有一套坐标（厘米），米格是它的一种**视图**。
 */
const val CM_PER_METRE = 100
