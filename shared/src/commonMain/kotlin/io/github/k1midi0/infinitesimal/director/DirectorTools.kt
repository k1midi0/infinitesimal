/**
 * 导演交给模型的那几只"手"（§8）。
 *
 * ## 两档给的手不一样，这是设计里的一条硬边界
 *
 * §1.4：**便宜的档位没有写权限。** 在导演内部，这条落成——快速档只有一只手（唤醒思考档），它连
 * `schedule` 都摸不到；改时间轴、长地形、放东西全在思考档手里。这不是省 token 的优化，而是
 * 「谁有能力改世界」这件事本身的形状：快速档每回合都醒着，如果它也能写，那么每一回合都是一次
 * 无人复核的写入。
 *
 * ## 为什么没有「切回快速档」那只手
 *
 * §8.5 说思考档觉得稳定了会调工具切回去。**这一刀不装它**：一次唤醒在模型沉默时就结束了，切回去
 * 意味着"这一次工作剩下的一半用便宜档跑"，而那要等导演变成一个跨回合长活的东西才成立
 * （§12 第 38 项）。提前装一只没人会正确使用的手，只会让它在历史里漂移。
 *
 * 参数刻意保持扁平（只有 string / integer），与判定那边同一个理由：移植过来的 `JsonSchema` 不支持
 * 嵌套对象与数组。
 */
object DirectorTools {

    // ── 快速档唯一的一只手 ──────────────────────────────────────────────────────────

    /**
     * 把思考档叫起来。
     *
     * 它是**换档**，不是"再叫一个人"——同一次工作里继续往下走，历史一段不重建（§8.5）。所以它最重要
     * 的部分是 `why`：那句话会留在上下文里，而思考档接手时要靠它知道自己为什么在这儿。
     */
    const val WAKE_THINKING = "wake_thinking"

    // ── 思考档的三只手 ─────────────────────────────────────────────────────────────

    /**
     * 往时间轴里放一件事。
     *
     * ## 为什么时间是"第几天 + 几点几分"而不是"多少分钟之后"
     *
     * 因为导演想事情的单位就是那个。它要说的是"第 3 天夜里，北门有一支队伍经过"（§1.3 的原话），
     * 不是"2592 分钟之后"。让代码去猜"夜里"是几点，就等于让代码替它下一半的判断；而让它自己把
     * "两个钟头之后"换算成钟点，才是它做得了、也看得出对错的一件事——**现在的时刻就印在它要读的
     * 那一段里**。
     *
     * ## 为什么没有"谁牵涉其中"这个参数
     *
     * [io.github.k1midi0.infinitesimal.world.TimelineEntry.actors] 那个字段现在没有任何东西在读它。
     * 加一个模型要填、而没人消费的参数，结果只是让它每次多写一句话，而且那句话会随着没有反馈而漂移。
     * **等日程与 NPC 进来（§3.2）再加。**
     */
    const val SCHEDULE = "schedule"

    /**
     * 长出一片地形，顺带放下点名的东西。
     *
     * 名字是 `grow` 而不是 `fill`：它是**生成**，与判定那三只直接改已有地形的 `fill_terrain` /
     * `dig_terrain` / `replace_terrain` 是两件事。判定改的是已经长好的地，导演长的是还没有的地
     * （§14.30）。
     */
    const val GROW_TERRAIN = "grow_terrain"

    const val LOOK_MAP = "look_map"

    /**
     * **给一个角色写它的状态循环**（§8.3、§14.44）。
     *
     * 它回答的是「**没人理它的时候，它此刻在干什么、在哪儿**」——而这一句是代码查表得出的，零模型调用。
     * 一个氛围 NPC 之所以"平时根本不是 AI"，全靠这张表有答案（§3.2）。
     *
     * ## 为什么时间是"从循环开始那一刻起的第几分钟"
     *
     * 因为循环是一只**定时器**：它从被写下的那一刻开始跑，而一件事发生在"跑了多久之后"。写成"一天里的
     * 第几分钟"会把两件事捆死——一个循环必须正好一天长，而你说的可以是**一天半**。时刻的量词也因此在
     * 提示词里说清：`0` 就是循环开始的第一瞬间。
     *
     * ## 为什么地点要给坐标
     *
     * 因为这一格的地点有两个用途，两个都要一个确定的点：**到点了代码把角色挪过去**（否则"它在酒馆里
     * 招呼客人"只是句好听话），以及**回归时判它到没到**（§14.44：这一条以前查不了，因为循环里没有
     * 位置）。
     *
     * ## 为什么一次要写全
     *
     * **整张替换**（§14.44）。作息是一张周期表，半张表读出来是错的答案：缺了 23:00 那一格，凌晨三点它会
     * 答"站在柜台后面招呼客人"。所以写来的就是它这一天的全部答案，旧的一格不留。
     */
    const val WRITE_CYCLE = "write_cycle"

    /**
     * 放一个人出来（§14.46）。
     *
     * ## 为什么是"放一个人"而不是"加一批 NPC"
     *
     * 因为一片街上该有三五个人这件事**不该由模型逐个数出来**——那是 `grow_terrain` 的活（`placements`
     * 那段注释：地标才该点名）。这一只手要的是**有名字、有来历、以后叫得出声的那一个**：酒馆老板的
     * 女儿、收了钱不办事的镖师、镇口那个谁也没见过几次的陌生人。
     *
     * ## 一个字段就分开了两档人
     *
     * `beats` 空 = **剧情角色**：它不自己走动，只在被点到名的时候才有人去演它。
     * `beats` 有 = **氛围角色**：代码按这张表把它挪来挪去，平时一次模型调用都没有（§3.2.1）。
     * 类型不单独存一个字段——它由结构决定（[CharacterWrite] 那段注释）。
     */
    const val SPAWN_CHARACTER = "spawn_character"

    /**
     * **给一个角色补背景**（§14.52、§3.2.1 的第 1 件事）。
     *
     * ## 它补的是哪一格
     *
     * §3.2.1：「转化的同时直接唤起思考档导演，由导演统筹三件事」，第 1 件是「**人设的追加**：这次事件
     * 给它添了什么设定」。而**它不是"把经历写进去"**（这一条是用户 2026-09-28 更正过的）：经历本来就在
     * 角色自己的上下文里（对话历史 + 事件总线），而这一只手要补的是**它本来该有、而开局那张卡没写的
     * 那一层背景**——一个氛围角色被问到哪里有酒馆、或者要被托付一条支线、或者要升成剧情角色时，原来
     * 那份简单的设定就不够了（"它其实是传奇铁匠的传人"）。所以它挂在这一刻：**氛围角色变成活跃角色**
     * 的那一下（`GameSession.wakeTheDirectorAboutTurningActive`）。
     *
     * ## 为什么按标题改，而不是"加一张"
     *
     * 因为补背景有两种形状：**添一层新的**（它其实是谁的传人）与**改写原来那一层**（原来写着「你不信任
     * 陌生人」，而它现在要托付的事需要它信任玩家）。所以语义是**标题对上的替换、对不上的追加**
     * （[CardPlanner]），两件事都在这只手里。
     *
     * ## 上限
     *
     * 卡是**每次唤醒都全文进提示词**的，所以有两条上限（一张 [CardPlanner.MAX_CARD_CHARS]、一个人合计
     * [CardPlanner.CARD_BUDGET_CHARS]）。到顶之后的出路是**改写**——既然改本来就在权限里，那比另造一套
     * "替代/删除"要省事，也不会让"它忘掉了什么"悄悄发生。
     */
    const val WRITE_CARD = "write_card"

    /** 快速档的手。**只有一只**，而且它不碰世界。 */
    val FAST: List<ToolDefinition> = listOf(
