package io.github.k1midi0.infinitesimal.world

import kotlinx.serialization.Serializable

/**
 * 一个**预设**：一份有名字的形状，是造东西的模板（附录 A.9）。
 *
 * ## 为什么要有它
 *
 * 世界里的形状是**我们自己造的**（A.9 定的），因为买不到、也画不全：一座小屋、一张桌子、一只酒杯，
 * 都要有人先造出一份形状来，之后世界里的东西才能有形状。造形状这件事由模型做（建模），而它的**产物
 * 不能只属于某一个物体**——同一张桌子会被造很多次。于是中间需要一层：**预设是工厂，成品是物体。**
 *
 * ## 它是工厂，不是引用
 *
 * A.9 那条原话是：**预设库是工厂，不是引用。** 从预设生成一个具体物体，是把形状**拷贝**一份；之后
 * 这个物体与预设再无关系，改它不影响任何别的物体。
 *
 * 在这里"拷贝"是白拿的：[VoxelShape] 是不可变的，里面全是只读的列表。所以"改一个物体的形状"永远是
 * **换掉它自己那一份**（`Entity.copy(shape = …)`），碰到不预设，也碰不到别的物体。A.9 想要的那条
 * 性质因此不是靠纪律维持的，而是**在数据模型上无法被违反**——与"变化等级不是模型填的枚举"（§4.1）
 * 是同一条思路。
 *
 * ## 两个身份，两个键
 *
 *  - [name]：**给人和模型看的短名字**（`half_oak_table`）。判定引用形状时用它。
 *  - [brief]：**当初那句要求**。它是**缓存键**——用户定的：同一句要求就该得到同一份形状。
 *
 * 分开，是因为两者要的东西相反：要求写给人看会啰嗦成一段话，而要求写成名字又会丢掉"这是被劈开的、
 * 断面粗糙的橡木方桌"里那些决定形状的词。
 *
 * ## 第三个身份：属性总结
 *
 * [category] 与 [tags] 是**给检索用的**（用户定的：对物体做属性总结，然后按关键词搜）。
 *
 * 它们与 [brief] 的分工是：brief 是一整句话，**写得越具体越没法搜**——"一棵被雷劈过的歪脖子橡树"
 * 与"一棵高大的橡树"逐字不同，而要找的是同一类东西；而"树木/橡树"这两个词能同时命中两者。
 *
 * 所以 exact 匹配（[brief]）与关键词检索（[category] + [tags]）**不是一回事，两个都留着**：前者是
 * 免费且不会选错的第一道关，后者是它落空之后的第二道关（[PresetLibrary.search]）。
 */
@Serializable
data class Preset(
    /** 短名字，只用小写字母、数字、下划线。 */
    val name: String,
    /**
     * 当初那句要求。**它是缓存的第一道关**——同一句要求不必再建模一次。
     */
    val brief: String,
    val shape: VoxelShape,
    val origin: Origin = Origin.GENERATED,
    /**
     * **一个类别**：这样东西属于哪一大类（`树木`、`家具`、`餐具`、`灯具`、`工具`）。
     *
     * 用户定的形状是"一个类别 + 一串标签"，不是一张固定字段表：类别用于粗筛（"我要一棵树"），
     * 标签用于细搜（"橡树"）。固定字段表搜起来更准，但很多物件填不满，空字段在提示词里就是噪声。
     *
     * 空白是允许的（老数据、或者建模时模型没写），只是那样它在类别这一维上搜不到。
     */
    val category: String = "",
    /**
     * **一串标签**：细搜用的词（`橡树`、`乔木`、`落叶`、`可攀爬`）。
     *
     * 与 [category] 一样由**建模那一步的模型写**（它刚画完那件东西，最清楚它是什么）——出厂包与
     * 生成包因此走同一条路，不会出现"出厂那批搜得到、现造的搜不到"。
     */
    val tags: List<String> = emptyList(),
) {

    /**
     * 这条预设是哪来的。
     *
     * **出厂与生成分开存，不混进同一个包**（用户定的）——出厂的那批随游戏走，生成的那批是这一局
     * 长出来的；混在一起，就再也说不清"哪些是我们自己带的、哪些是模型现场编的"，而这条信息在排查
     * 一份难看的形状时正是第一个要看的。
     */
    @Serializable
    enum class Origin {
        /** 随游戏带来的。 */
        BUILTIN,

        /** 建模长出来的。 */
        GENERATED,
    }
}
