package io.github.k1midi0.infinitesimal.world

import kotlinx.serialization.Serializable

/**
 * 一个**预设**：一份有名字的形状，是造东西的模板（附录 A.9）。
 *
 * ## 为什么要有它
 *
 * 世界里的形状是**我们自己造的**（A.9 定的），因为买不到、也画不全：一座小屋、一张桌子、一只酒杯，
 * 都要有人先造出一份形状来，之后世界里的东西才能有形状。造形状这件事由模型做（建模），而它的**产物
 * 不能只属于某一个物体**——同一张桌子会被造很多次。于是中间需要一层：**预设是工厂，成品是物体。**
 *
 * ## 它是工厂，不是引用
 *
 * A.9 那条原话是：**预设库是工厂，不是引用。** 从预设生成一个具体物体，是把形状**拷贝**一份；之后
 * 这个物体与预设再无关系，改它不影响任何别的物体。
 *
 * 在这里"拷贝"是白拿的：[VoxelShape] 是不可变的，里面全是只读的列表。所以"改一个物体的形状"永远是
 * **换掉它自己那一份**（`Entity.copy(shape = …)`），碰到不预设，也碰不到别的物体。A.9 想要的那条
 * 性质因此不是靠纪律维持的，而是**在数据模型上无法被违反**——与"变化等级不是模型填的枚举"（§4.1）
 * 是同一条思路。
 *
 * ## 两个身份，两个键
 *
 *  - [name]：**给人和模型看的短名字**（`half_oak_table`）。判定引用形状时用它。
 *  - [brief]：**当初那句要求**。它是**缓存键**——用户定的：同一句要求就该得到同一份形状。
 *
 * 分开，是因为两者要的东西相反：要求写给人看会啰嗦成一段话，而要求写成名字又会丢掉"这是被劈开的、
 * 断面粗糙的橡木方桌"里那些决定形状的词。
 */
@Serializable
data class Preset(
    /** 短名字，只用小写字母、数字、下划线。 */
    val name: String,
    /**
     * 当初那句要求。**它是缓存键**——同一句要求不必再建模一次。
     */
    val brief: String,
    val shape: VoxelShape,
    val origin: Origin = Origin.GENERATED,
) {

    /**
     * 这条预设是哪来的。
     *
     * **出厂与生成分开存，不混进同一个包**（用户定的）——出厂的那批随游戏走，生成的那批是这一局
     * 长出来的；混在一起，就再也说不清"哪些是我们自己带的、哪些是模型现场编的"，而这条信息在排查
     * 一份难看的形状时正是第一个要看的。
     */
    @Serializable
    enum class Origin {
        /** 随游戏带来的。 */
        BUILTIN,

        /** 建模长出来的。 */
        GENERATED,
    }
}
