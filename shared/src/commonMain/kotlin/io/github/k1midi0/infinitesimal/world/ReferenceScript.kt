package io.github.k1midi0.infinitesimal.world

import kotlinx.serialization.Serializable

/**
 * **一条参考剧本**（§8.4、§14.55）——**第一层**。
 *
 * ## 它与 [Script] 是两样东西
 *
 * [Script] 是**这个世界的**一条线（导演照着这一局的地图与人写出来的，可改、可标注，进存档）。
 * 它是**世界之外的**一条故事骨架：用户给一部小说或者剧本，模型把它**总结拆分**成一堆这样的东西，
 * 存成一个**库**。库不属于任何一局游戏。
 *
 * 两层的关系是一句话：**导演照着参考剧本，把它填成这个世界的剧本**（[Script.source] 记的就是那份
 * 参考剧本的 id）。世界需要它**知道更多**时添东西、需要它与原来不同时改写——那都是第二层的事。
 *
 * ## 为什么它必须"抛弃角色背景"
 *
 * 用户定的原文：「用户提供小说、剧本等，模型总结拆分出**抛弃角色背景等**概括性的参考剧本保存」。
 *
 * 理由是它要被填进**任何一个**世界：一条写着"卡尔·莫恩是个被逐出师门的铁匠"的参考剧本，只有那一个
 * 世界能用；而写着「一个被逐出师门的手艺人，他的旧师父还在这一带」的那一条，可以填成本世界的矮人、
 * 也可以填成玩家明天才遇见的那个人。所以 [body] 里**只许出现处境与角色位**（"一个欠了债的人""债主"
 * "一个知情者"），**不许出现具体的人名、地名、头衔、家族、门派**——那些是第二层要填的东西。
 *
 * ## 成本那一条与 [Script] 一样
 *
 * [summary] 是唯一常驻提示词的那一段（导演每次开工看的那份清单里只有 id + 标题 + 概括）；[body] 要
 * 打开才看（`look_reference`）。所以离线拆分时上限照 [ScriptPlanner] 那两档来（摘要 200 字、正文
 * 2000 字），两份东西的"每次唤醒付多少"才是同一个数。
 */
@Serializable
data class ReferenceScript(
    /** 代号。**由拆分那一步定**（世界那一层由导演自己起名，这一层不是）。 */
    val id: String,
    /** 一句话的标题。 */
    val title: String,
    /** 概括（200 字以内）：**这一条是什么**。它是这一层唯一常驻提示词的那一段。 */
    val summary: String,
    /** 骨架（2000 字以内）：这件事怎么发生、谁卷进来、玩家可能怎么撞上、有哪几种走法。**没有人名地名。** */
    val body: String,
    /** 出处：从哪一部作品（或者哪一个文件）里拆出来的。库由好几部拼起来时，它认得出这条是从哪儿来的。 */
    val from: String = "",
)

/**
 * **一个参考剧本库的文件形状**（§14.55）。
 *
 * 与 [PresetPack] 同一个道理，但这个**不需要**那个网格编码：预设之所以要转成文本，是因为一堆坐标三元
 * 组在 JSON 里又大又读不出来；参考剧本本来就是文本。
 *
 * [chunksDone] 是**离线工具**的进度（它按"第几段原文"增量跑，中断之后重跑不该重做已经付过钱的那几段）。
 * 它跟着库一起存在文件里，而不是另开一个状态文件——那样"库"与"拆到哪儿了"有可能不是同一份，而症状是
 * 某一段被拆了两遍（库里出现两条一样的线）。
 */
@Serializable
data class ReferencePack(
    val version: Int = FORMAT,
    /** 这一份文件是从哪个源文本拆出来的（工具填；手写的出厂种子写"出厂种子"）。 */
    val from: String = "",
    /** 已经拆到第几段（原文本的分段序号，从 0 起）。手写的出厂种子是 0。 */
    val chunksDone: Int = 0,
    val scripts: List<ReferenceScript> = emptyList(),
) {
    companion object {
        /** 文件形状的版本。**改动字段的语义与必有时加一**，加字段（带默认值）不用（与存档那份同一条）。 */
        const val FORMAT: Int = 1
    }
}

/** 把库列成给导演看的那一份清单（id + 标题 + 概括）。**正文不在里面**，那是 `look_reference` 的事。 */
fun List<ReferenceScript>.listing(): String =
    if (isEmpty()) {
        "（参考剧本库里一条都没有）"
    } else {
        joinToString("\n") { "- ${it.id}｜${it.title}\n    ${it.summary.trim()}" }
    }
