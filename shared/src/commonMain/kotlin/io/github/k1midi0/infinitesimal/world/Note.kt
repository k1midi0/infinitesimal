package io.github.k1midi0.infinitesimal.world

import kotlinx.serialization.Serializable

/**
 * **笔记**：角色自己决定「这件事我得记住」，写下来的一条（§6.3、§6.6）。
 *
 * ## 它与 [Todo] 是两样东西，分界线是"打算"与"记住"
 *
 * | | [Todo] 待办 | 这里 |
 * |---|---|---|
 * | 回答 | 它打算在某个时刻**做什么** | 有件事它**不能忘** |
 * | 到点 | 会到点，到点被提醒 | **永远注入**，不看时刻 |
 * | 谁读 | 模型 | 模型 |
 *
 * 两样都进提示词、都由角色自己写，所以看着像一件事。但它们的**失效方式**完全不同：待办做完了就
 * 自然不算数（那个时刻过去了），而一条笔记做完了**不会自己失效**——「玩家欠我一杯酒」在他还清之后
 * 仍然是那句话，得有人明确地把它撤掉。这就是 [supersedes] 的用处（§6.4）。
 *
 * ## 与压缩的分工是硬的（§6.3）
 *
 * **压缩是自动的、有损的、模型看不见的；笔记是主动的、常驻注入的、不参与压缩的。** 所以"重要的东西
 * 不能被压掉"这件事靠的是笔记与待办，不是靠把阈值调高。压缩压的是消息数组，而笔记**不在那个数组里**
 * ——它每一轮都作为提示词的一节被重新拼出来，压多少次都不会碰到它。
 *
 * ## 只能追加、只能被替代，永不删除（§6.4）
 *
 * 撤销一条笔记**不是把它删掉**，而是写一条新的、在 [supersedes] 里点名它。理由与「记录永不改写」
 * 一模一样：你要能在事后回答"它当时为什么这么想"。所以 [Note.supersedes] 指向的那条**仍然在
 * [Entity.notes] 里**，只是不再注入（见 [List<Note>.live]）。
 *
 * 混在一起会出的事写在这里，免得日后有人"顺手"把 supersede 换成删除：**注意事项会退化成一堆互相
 * 矛盾的历史陈述，而模型会同时相信它们**。这种错不报错、不崩，只表现为"它偶尔基于过期事实做事"
 * ——最难查的一类 bug。
 *
 * @property id 这条笔记自己的编号（`n1`、`n2`……），**每个角色从 1 数起**。它是模型点名替代一条旧
 *   笔记时唯一的抓手，所以它必须出现在提示词里。
 * @property text 那条内容，一句话。
 * @property tag 一个粗标签（「人」「事」「约」之类）。**它是给检索留的位置**——现在笔记全量注入、
 *   用不上它，但 §6.5 那套关键词检索落地时，读的就是这一栏。
 * @property at 写下来的时刻。**过期的笔记也要给**——与待办同一条理由：「三天前记下的事」比"什么都不
 *   提"更接近它自己的记忆。
 * @property supersedes 这条笔记替代了哪一条（`n1` 这样）。`null` = 它只是新添的一条。
 */
@Serializable
data class Note(
    val id: String,
    val text: String,
    val tag: String = "",
    val at: WorldTime,
    val supersedes: String? = null,
)

/**
 * **现在还算数的那些**：没有被任何一条更新的笔记点名替代的。
 *
 * 被替代的那些永远留在存储里（§6.4），但**不进提示词**——不然模型会同时看到"玩家欠我一杯酒"与
 * "那杯酒他已经还了"，而它会两条都信。
 */
fun List<Note>.live(): List<Note> {
    val replaced = mapNotNullTo(mutableSetOf()) { it.supersedes }
    return filter { it.id !in replaced }
}

/** 它替代了的那些，按被替代的顺序。**只给测试与探针看**，注入用的是 [live]。 */
fun List<Note>.replaced(): List<Note> = filter { note -> any { it.supersedes == note.id } }

/**
 * 下一条该用的编号：`n1`、`n2`……
 *
 * **从已有那些里数出来，不另存一个计数器。** 编号是笔记表自己的性质，多存一个计数器就多一处会与它
 * 对不上的地方——而"编号重复"的症状是模型指着一条新笔记说出了旧内容，看着完全正常。
 *
 * 它只要求**在一个角色自己那几条里唯一**：笔记是按所有者存在各自的 [Entity] 上的（§6.6：NPC 只能读
 * 自己的笔记），两个角色的 `n1` 永远不会在同一份提示词里碰面。
 */
fun List<Note>.nextId(): String {
    val used = mapNotNullTo(mutableSetOf()) { it.id.removePrefix("n").toIntOrNull() }
    var n = 1
    while (n in used) n++
    return "n$n"
}
