                "所以要紧的事（谁欠你什么、你答应了谁什么、你打听到的消息）该记在这里。" +
                "一条一句话，别把整段对话抄进来；不值得记的就别记。" +
                "**记满了要撤掉一条旧的**：把它的编号写进 supersedes——那条以后就不再出现了，" +
