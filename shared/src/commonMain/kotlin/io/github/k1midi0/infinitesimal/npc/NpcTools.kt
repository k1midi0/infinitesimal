package io.github.k1midi0.infinitesimal.npc

import io.github.k1midi0.infinitesimal.llm.ToolDefinition
import io.github.k1midi0.infinitesimal.llm.int
import io.github.k1midi0.infinitesimal.llm.text
import io.github.k1midi0.infinitesimal.llm.tool

/**
 * AI 角色交给模型的那几只"手"（§3.4、§5）。
 *
 * ## 一回合里说、做、移动**各一次**
 *
 * 玩家的一轮是「说的话 + 做的事 + 移动」一次提交（§4.3），而 AI 角色这一侧现在与它对齐了：**说一句话
 * 一次、做一个动作一次、移动一次**，各自独立（可以只说、只做、只走，也可以三样都有）。封的是**被记下
 * 的那几件事**：**被驳回不算**——判定驳回之后它照样能改一改再试（那是 §1.3 那条回路），因为驳回不是
 * 它做过的事。
 *
 * 判据不是「一回合只发一次请求」：一次唤醒里它可以先看一眼（[LOOK]）、记一条笔记（[NOTE]）、宣告
 * 回归（[ARRIVE]）——**这些都不占那三个名额**。它们不是"玩家那一轮的三样输入"，而是它自己过程里的
 * 动作，[ARRIVE] 更是"这一趟到这儿了"那句话本身。
 *
 * ## 为什么 `say` 也得是一只工具
 *
 * 与 §1.2 同一条理由：**说话必须是一个动作。** 如果模型的正文就是"它说出的话"，那么每一次调用都会
 * 产生一句台词——包括它只是在思考、只是在记录的时候。做成一只手之后，"说了什么"变成一个可数的、
 * 可回放的条目，而模型的正文退回到它本来的位置：过程，不是结果。
 */
object NpcTools {

    /**
     * 开口说一句话。
     *
     * **一回合最多一句**（上面那段类注释）。这不是形式要求——**每一句都会当场被听见**，而"一口气说
     * 三段"在世界上不存在对应物（§5.1 的投递单位是句子）：想说的分两次说，那是两回合的事。
     */
    const val SAY = "say"

    /**
     * 做一个动作。
     *
     * **它成不成立由判定裁决**，理由见上面那段类注释。参数只有"想做什么"，因为后果、影响范围、
     * 够不够得着全在判定那边算——角色这边多说一分，就多一分与裁决打架的机会。
     *
     * **一回合最多成功一次。** 判成立之后这只手就关上了；而**被驳回不算**——驳回是一次"不成，因为…"，
     * 它读完那个理由可以换个做法再调一次。
     */
    const val ACT = "act"

    /**
     * **移动**：走到哪去。
     *
     * 它与 [ACT] 分开是有理由的。玩家那一轮的三样输入里"移动"是独立的一栏，而在这之前角色这边**没有
     * 任何设位置的手**——它要挪一步只能把"我走过去"混在动作那句意图里。现在两件事分开：`act` 是"我在
     * 这儿做点什么"，`move` 是"我要到那儿去"。
     *
     * ## 它不自己写坐标
     *
     * **位置由判定写，不由角色写**（§3.2.5、§12 第 23 项："位置不在循环里，而是一个判定随时会改的
     * 事实"）。所以这只手给的是**意图**（"我走到柜台后面"），而不是 `(x, y, z)`——判成之后它是一条
     * [Consequence.Move][io.github.k1midi0.infinitesimal.judge.Consequence.Move]，坐标由判定算，
     * 而"走不到"这件事也由判定驳回（够不够得着、脚下有没有地，那些几何是代码算好写在它眼前的）。
     *
     * 与 [ACT] 同样的封法：**一回合最多成功一次，被驳回的可以再来。**
     */
    const val MOVE = "move"

    /**
     * **安排一件将来要做的事**——写进它自己的 [io.github.k1midi0.infinitesimal.world.Todo]（§3.2.5）。
     *
     * 这是「**角色自己也能写待办**」那条设计的落点，而它与[状态循环][io.github.k1midi0.infinitesimal.world.Cycle]
     * 不是一个东西：循环是作息（谁什么时候开门），归导演；待办是打算（明天去修铠甲），归它自己。
     *
     * **到点不等于自动发生**：到点了它只是出现在提示词里，那件事照常要过判定（这只手不产生后果，
     * 世界一个字都不会动）。
     */
    const val PLAN = "plan"

    /**
     * **查看总线上某一条的细节**（§6.1、§14.39）。
     *
     * 事件总线只把**被指向的**给全文，其余只给「编号 + 一行标题」——因为「被指向」与「恰好在场」是
     * 两回事，而模型该看得出这个差别，并自己决定要不要花一次调用去查。这只手就是那次"查"。
     *
     * 它**查不到更早的**：总线不带历史，那不是缺陷，是"自然遗忘"（§1.5 的那条根决策由底下的记录层
     * 保住，模型这一侧看不见）。
     */
    const val LOOK = "look"

    /**
     * **把最老的那一段历史压成一条摘要**（§6.1、§14.40）。
     *
     * 只在提示词里明说"该收一收了"的时候才用它——触发条件是上下文的估算超过阈值，而那件事是**代码**算
     * 出来告诉它的（`ContextSettings.compressAfterTokens`）。它不自己判断该不该压：**该不该压是一件
     * 能看到真数的事，而它看不到**。
     *
     * 压出来的摘要自己以后再超阈，就再压一次——那就是第 2 级、第 3 级。**"自然遗忘"的形状就是这么来的**：
     * 越早的事被压得越狠，而它不会消失，只会变短。
     */
    const val COMPACT = "compact"

    /**
     * **记下一条不能忘的事**（§6.3、§6.6）。
     *
     * 它与压缩是同一个问题的两面，而分工是硬的：**压缩是自动的、有损的、模型看不见的；这一只是主动的、
     * 常驻注入的、不参与压缩的**。所以超阈时提示词里那句话才对——「要留在身上的事，就写进那条摘要里」
     * 之外还有一条更硬的路：**写进笔记**。摘要会被再压一次，笔记不会。
     *
     * ## 它只能是"追加 + 替代"，不能是"改写 + 删除"
     *
     * 撤销一条笔记的办法是写一条新的、在 `supersedes` 里点名它（§6.4）。被替代的那条**仍然在存储里**，
     * 只是不再出现在它眼前——这样事后才能回答"它当时为什么这么想"。而"注意事项"与"发生过的记录"因此
     * 不会混成一堆互相矛盾、却被同时相信的陈述。
     */
    const val NOTE = "note"

    /**
     * **回到自己的循环上**（§3.2.1、§12 第 46 项）。
     *
     * 一只活跃氛围 NPC 走到"这一趟结束了"的时候用它。它只在**脱轨的那些角色**手上——一个在循环里的
     * 角色没有这条要说的话。
     *
     * ## 为什么由它自己宣告，而不是代码算出来
     *
     * 循环那一格只有一句状态、没有位置（§12 第 23 项）。所以代码没有可靠的判据去判"到没到"，
     * 而**那句话只有它知道**。于是分工照旧：**模型提出，代码只确认它有没有资格说这句话**——此刻那一格
     * 正是它说要回的那一格，才放行（`Active.canArrive`）。
     *
     * ## 它不记任何东西
     *
     * 这一趟的经历留在两处本来就在的地方：**对话历史**（累积的多轮上下文，压过也在）与**它自己写的
     * 那些笔记**。为回归再写一份摘要是第二种记法，而两种记法迟早会不一致。
     */
    const val ARRIVE = "arrive"

    val ALL: List<ToolDefinition> = listOf(
        tool(
            SAY,
            "开口说一句话。**说出来就收不回来了**——当场就会被在场的人听见。" +
                "**一回合只说一句**：想多说，那是下一回合的事。",
            text("text", "你要说的那句话，直接写台词，不要加旁白、不要把自己名字写进去。"),
        ),
        tool(
            ACT,
            "做一个动作。**它成不成立不由你决定**：有一个独立的判定系统会看这个动作合不合理、" +
                "你够不够得着、世界里现在是什么状况，然后告诉你做成了没有。" +
                "被驳回是常事，驳回理由会说清为什么，你可以换个做法再来一次。" +
                "**不要在这里描述结果**——只写你要做什么。" +
                "**一回合最多做成一件**；想走动就走 `move` 那只手。",
            text(
                "intention",
                "用第一人称写清你要做什么（例如「我伸手去够桌上那只杯子」）。" +
                    "一句话一件事，不要写成一段计划。",
            ),
            text(
                "targets",
                "这个动作指向的是**哪些东西的 id**，多个用空格隔开。" +
                    "**拿不准就不填**——判定会自己对齐它该落在哪些东西上。",
            ),
            optional = listOf("targets"),
        ),
        tool(
            MOVE,
            "**走到别处去。** 写清你要去哪儿（「我绕到柜台后面」、「我往门口走两步」）。" +
                "**坐标不由你定**：判定会看这一路的距离与脚下有没有地，成不成、落在哪个坐标，由它算。" +
                "走不到会被驳回，理由会说清为什么——例如那中间隔着东西。" +
                "**一回合最多走成一次**；要在这儿动手做事就用 `act`。",
            text("intention", "用第一人称写清你要去哪儿（例如「我绕到柜台后面去」）。"),
        ),
        tool(
            PLAN,
            "给自己安排一件**将来**要做的事。到点之后它会在你的提示词里出现，提醒你去做——" +
                "**而它不会自己发生**：到时候你还是得真的动手，那件事照常要过判定。" +
                "它不影响眼前这一刻，所以只有真的有事要安排时才用它。",
            int("day", "第几天（今天是第几天，看上面【现在】那一段）"),
            int("hour", "几点，0–23"),
            int("minute", "几分，0–59，不填就是 0"),
            text("what", "那件事，一句话（例如「去东街找那个木匠」）"),
            optional = listOf("minute"),
        ),
        tool(
            LOOK,
            "看**这一回合**你附近某件事的细节。提示词里【这一片里刚刚发生的事】那些**没写全文的**条目，" +
                "想看内容就把它的编号给这只手（形如 e12）。" +
                "**看不到更早的，也看不到远处的**——看不到就是看不到，" +
                "不要因为好奇去猜。",
            text("id", "那条的编号，形如 e12"),
        ),
        tool(
            COMPACT,
            "把**最老的那一段**历史压成一条摘要。只在你被告知「该收一收了」时用它——" +
                "那段提示里会给出建议的范围。压完之后那一段的细节就不再逐字保留，" +
                "所以**该留下的事实要写进摘要里**。",
            int("from", "起始位置号（提示里的 h 后面那个数）"),
            int("to", "结束位置号（含）"),
            text("summary", "那一段里发生过什么、结果如何。写事实，不要写感想——它是给你自己以后看的。"),
            text("topic", "一句话主题，便于以后认出来。可以不填。"),
            optional = listOf("topic"),
        ),
        tool(
            NOTE,
            "记下一件**你不能忘的事**。写下来的东西**每一轮都会回到你眼前**，" +
