                "那一行写的那句话。**代码只认那一格**：填错了会被驳回，理由会说清现在到底是哪一格。" +
                "回去之后你不再是活跃的：你自己的笔记不再出现在你眼前（它们还留着），" +
                "你也要等有人再跟你说话才会醒过来。",
            text("state", "你要回到的那一格的状态原文（照抄提示词里的那一行）。"),
        ),
