package io.github.k1midi0.infinitesimal.world

import kotlinx.serialization.Serializable

/**
 * **待办**：某个时刻 + 一件事（§3.2.5）。
 *
 * ## 它与 [Cycle] 是两样东西，分界线是消费者
 *
 * | | [Cycle] 状态循环 | 这里 |
 * |---|---|---|
 * | 回答 | 无人值守时它在干什么 | 它打算在某个时刻做什么 |
 * | 谁读 | **代码**（状态机），零模型调用 | **模型**，进提示词 |
 * | 谁写 | 生成时由导演写 | 导演写；**角色自己也能写** |
 *
 * 所以循环可以有成百上千条而成本零增量，待办只能属于少数几个角色。把两样并成一样，就等于要么让
 * 代码读不了（成本爆炸），要么让模型看不到（角色没有打算）。
 *
 * ## 到点之后**不是自动发生**，而是提醒模型
 *
 * 它是「时刻 + 一回事」，不是闹钟。到点了，它出现在那个角色的提示词里——「你打算做的事（已经到点
 * 了）：去修铠甲」——然后由那个角色自己决定去不去、怎么去，而那件事**照常要过判定**（§1.2 改世界
 * 必须显式动手）。这条线不能松：如果到点就自动发生，世界会出现一批没人做过、也没有痕迹的改变。
 *
 * ## 「止于无限」那种待办
 *
 * 路边受伤的法师有一条「等待救援」，起于它诞生、**止于无限**——那不过是把 [at] 写成一个很远的将来。
 * 形状不用为它改：待办永远是「某个时刻之后该做的事」，而"一直等"就是"那个时刻永远不会到"。
 *
 * @property at 什么时候该做。到了或者过了，它就出现在提示词里。
 * @property what 那件事，一句话。
 */
@Serializable
data class Todo(val at: WorldTime, val what: String)

/**
 * 此刻该提醒它的那几条：**已经到点或已经过期**的，按时刻排。
 *
 * 过期的也要给——它可能一直没被唤醒。「三天前打算修铠甲」比"什么都不提"更接近它自己的记忆。
 */
fun List<Todo>.due(now: WorldTime): List<Todo> = filter { it.at <= now }.sortedBy { it.at }
