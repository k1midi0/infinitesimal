package io.github.k1midi0.infinitesimal.config

/**
 * **作息那一层的旋钮**（§14.50）。
 *
 * 与 [ContextSettings] 分开，是因为它们回答的是两个不同的问题：那一个管"一段对话长到什么时候该压"，
 * 这一个管"**一个脱离了日子的角色，多久没回来就该让导演重看它一眼**"。合成一个类的话，那个类名会开始
 * 撒谎——而名字撒谎的代价是下一个人往里放不该放的东西。
 *
 * 现在只有一格。一格也值得单独一个类：它有一个**默认值 + `require`** 的形状要守，而这一条判据在测试与
 * 探针里必须调得动（真等三百六十分钟是验不了的）。
 */
data class ScheduleSettings(
    /**
     * **脱离自己的日子超过这么多世界分钟，就该让导演重看它那一格**（§14.50、设计文档 §3.2.2）。
     *
     * ## 为什么是"世界分钟"，以及那条看似反直觉的性质
     *
     * 世界钟**只在玩家按「等到…」时走**（`session/FastForward.kt` 是全项目唯一推进它的地方）。所以玩家
     * 原地不动时，一个被关起来的角色**不会**被判超时——而这是对的：世界才过了几分钟，它确实只是刚被
     * 关进去。判据算的是世界里的时间，不是玩家敲了几次回车。
     *
     * ## 为什么是半天
     *
     * 360 分钟 = 六小时。挑它的理由与 §3.2.1 那条设计有关：回归的判据本应是"**回到循环上**"这件有意
     * 义的事，而不是一个计时器（原话：「这比'等一段时间'高明」）。所以这一条**越晚触发越好**——它是
     * 兜底，不是主路。六小时意味着：玩家得真的把它锁起来、并且让世界走过小半天，导演才会被叫起来。
     *
     * 一天那个数（1440）也说得通，但那会让"被带走"这件事在大多数一局里永远修不好；三十分钟又会让
     * "它只是刚被揍了一顿、还没走回去"也被当成回不去。
     */
    val activeTooLongMinutes: Int = DEFAULT_ACTIVE_TOO_LONG,
) {
    init {
        require(activeTooLongMinutes > 0) { "超时得是正数，收到 $activeTooLongMinutes" }
    }

    companion object {
        const val DEFAULT_ACTIVE_TOO_LONG: Int = 360
    }
}
